"""Pack the East Side Gallery bay renders as small alpha WebPs plus JS anchors."""
import json
import hashlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.claude/review/71/render-parts'
OUT = ROOT / 'assets/landmarks'
OUT.mkdir(parents=True, exist_ok=True)
manifest = json.loads((SOURCE / 'manifest.json').read_text())
manifest['packerSha256'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
parts = {}
for part, data in manifest['parts'].items():
    path = OUT / f'east-side-gallery-{part}.webp'
    image = Image.open(SOURCE / f'{part}.png').convert('RGBA')
    assert image.size == (data['width'], data['height'])
    assert image.getchannel('A').getextrema() == (0, 255)
    # Crop only top and bottom: every bay keeps the same width and centre, so tiles line up.
    _, y0, _, y1 = image.getchannel('A').getbbox()
    units_per_pixel = data['worldWidth'] / image.width
    data['bottom'] += (image.height - y1) * units_per_pixel
    image = image.crop((0, y0, image.width, y1))
    data.update(width=image.width, height=image.height, worldHeight=image.height * units_per_pixel)
    image.save(path, 'WEBP', quality=84, method=6)
    parts[part] = {'src': str(path.relative_to(ROOT)), **{k: data[k] for k in ('width', 'height', 'worldWidth', 'worldHeight', 'bottom')}}
    data['bytes'] = path.stat().st_size
    data['webpSha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
    print(path.relative_to(ROOT), data['bytes'], image.size)
(ROOT / 'js/gallery-sprite-data.js').write_text(
    '// Generated by tools/build-gallery-sprites.py; source and anchors in assets/landmarks/gallery-provenance.json.\n'
    f'export const GALLERY_PITCH = {manifest["pitch"]};\n'
    'export const EAST_SIDE_GALLERY_ART = ' + json.dumps(parts, indent=2) + ';\n')
(OUT / 'gallery-provenance.json').write_text(json.dumps(manifest, indent=2) + '\n')
