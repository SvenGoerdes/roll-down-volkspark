# Packs the frames from tools/blender/render.py into one WebP sheet per clip and writes js/figure-sheets.js (ADR 0018).
# python3 tools/build-sprites.py <frames_dir>   (frames_dir/<figure>/<clip>/NN.png plus meta.json per figure; needs Pillow)
import glob, json, math, os, sys
from PIL import Image

SRC = sys.argv[1]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
MAX_W = 2048     # keep sheets small enough for every phone GPU
QUALITY = 80

sheets = {}
total = 0
for fig in sorted(os.listdir(SRC)):
    meta_path = os.path.join(SRC, fig, 'meta.json')
    if not os.path.exists(meta_path):
        continue
    meta = json.load(open(meta_path))
    out_dir = os.path.join(ROOT, 'assets', 'figures', fig)
    os.makedirs(out_dir, exist_ok=True)
    sheets[fig] = {}
    for clip, m in meta.items():
        if clip == '_':
            continue
        frames = sorted(glob.glob(os.path.join(SRC, fig, clip, '*.png')))
        assert len(frames) == m['n'], f'{fig}/{clip}: {len(frames)} frames, meta says {m["n"]}'
        cols = min(m['n'], MAX_W // m['w'])
        rows = math.ceil(m['n'] / cols)
        sheet = Image.new('RGBA', (cols * m['w'], rows * m['h']), (0, 0, 0, 0))
        for i, f in enumerate(frames):
            sheet.paste(Image.open(f).convert('RGBA'), ((i % cols) * m['w'], (i // cols) * m['h']))
        path = os.path.join(out_dir, f'{clip}.webp')
        sheet.save(path, 'WEBP', quality=QUALITY, method=6)
        size = os.path.getsize(path)
        total += size
        print(f'{fig}/{clip}.webp  {sheet.width}x{sheet.height}  {size // 1024} KB')
        sheets[fig][clip] = {k: m[k] for k in ('n', 'w', 'h', 'ax', 'ay', 'loop', 'head') if k in m} | {'cols': cols}
print(f'total {total // 1024} KB')

with open(os.path.join(ROOT, 'js', 'figure-sheets.js'), 'w') as f:
    f.write('// Generated by tools/build-sprites.py from the Blender renders (ADR 0018). Do not edit by hand.\n')
    f.write('// Per clip: frame count n, frame size w×h, columns in the sheet, anchor ax/ay (the ball centre, in px),\n')
    f.write('// loop, and for dazed the head position (for the stars). Sheets: assets/figures/<figure>/<clip>.webp\n')
    f.write(f'export const PPU = {meta["_"]["ppu"]}; // sprite pixels per figure unit (a figure is ~1.8 units tall)\n')
    f.write('export const SHEETS = {\n')
    for fig, clips in sheets.items():
        f.write(f'  {fig}: {{\n')
        for clip, m in clips.items():
            f.write(f'    {json.dumps(clip)}: {json.dumps(m, separators=(", ", ": "))},\n')
        f.write('  },\n')
    f.write('};\n')
