"""Pack the reviewed Blender part renders as small alpha WebPs plus JS anchors."""
import json
import hashlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.claude/review/28/render-parts'
OUT = ROOT / 'assets/landmarks'
OUT.mkdir(parents=True, exist_ok=True)
manifest = json.loads((SOURCE / 'manifest.json').read_text())
manifest['packerSha256'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
parts = {}
for part, data in manifest['parts'].items():
    path = OUT / f'brandenburg-gate-{part}.webp'
    image = Image.open(SOURCE / f'{part}.png').convert('RGBA')
    assert image.size == (data['width'], data['height'])
    assert image.getchannel('A').getextrema() == (0, 255)
    x0, y0, x1, y1 = image.getchannel('A').getbbox()
    units_per_pixel = data['worldWidth'] / image.width
    data['bottom'] += (image.height - y1) * units_per_pixel
    image = image.crop((x0, y0, x1, y1))
    data.update(width=image.width, height=image.height,
                worldWidth=image.width * units_per_pixel, worldHeight=image.height * units_per_pixel)
    image.save(path, 'WEBP', quality=86, method=6)
    parts[part] = {'src': str(path.relative_to(ROOT)), **{k: data[k] for k in ('width', 'height', 'worldWidth', 'worldHeight', 'bottom')}}
    data['bytes'] = path.stat().st_size
    data['webpSha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
    print(path.relative_to(ROOT), data['bytes'], image.size)
(ROOT / 'js/gate-sprite-data.js').write_text('// Generated by tools/build-gate-sprites.py; source and anchors in assets/landmarks/provenance.json.\nexport const BRANDENBURG_GATE_ART = ' + json.dumps(parts, indent=2) + ';\n')
(OUT / 'provenance.json').write_text(json.dumps(manifest, indent=2) + '\n')
